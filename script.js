const animatedText = document.getElementById("animatedText");
const words = text.split(/(\s+|\n)/); // بيقسم الكلام بس بيحتفظ بالمسافات والـ enter
let i = 0;

function showWords() {
    if (i < words.length) {
        if (words[i] === '\n') {
            animatedText.appendChild(document.createElement('br'));
        } else if (words[i].trim() !== '') {
            const span = document.createElement('span');
            span.className = 'word';
            span.style.animationDelay = `${i * 0.08}s`;
            span.textContent = words[i];
            animatedText.appendChild(span);
        } else {
            // دي المسافة العادية
            animatedText.appendChild(document.createTextNode(' '));
        }
        i++;
        setTimeout(showWords, 80); // سرعة ظهور الكلمات
    }
}

window.addEventListener('load', showWords);